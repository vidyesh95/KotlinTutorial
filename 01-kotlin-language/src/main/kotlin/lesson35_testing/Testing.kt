// §6. Table-driven tests: many cases, one test body
// ───────────────────────────────────────────────────────────────────────────
// (JUnit's @ParameterizedTest needs the extra junit-jupiter-params library;
// a plain loop over a table works everywhere.)

fun section6TableDriven() {
    println("§6")
